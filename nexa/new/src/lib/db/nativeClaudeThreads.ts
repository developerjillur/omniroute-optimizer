import { createHash } from "node:crypto";
import { getDbInstance } from "./core";

const NAMESPACE = "native_claude_thread_owners";
const TTL_MS = 24 * 60 * 60 * 1000;
const MAX_RECORDS = 10_000;
let lastPrunedAt = 0;

function key(sessionId: string, messageId: string): string {
  return createHash("sha256")
    .update(sessionId.toLowerCase())
    .update("\0")
    .update(messageId)
    .digest("hex");
}

/** Retain ownership only; no prompts, credentials or response content are stored here. */
export function saveNativeClaudeThreadOwner(
  sessionId: string,
  messageId: string,
  connectionId: string,
  now = Date.now(),
  cacheGroupTag: string | null = null
): void {
  if (!sessionId || !/^msg_[A-Za-z0-9_-]{1,200}$/.test(messageId) || !connectionId) return;
  const db = getDbInstance();
  db.prepare("INSERT OR REPLACE INTO key_value (namespace, key, value) VALUES (?, ?, ?)").run(
    NAMESPACE,
    key(sessionId, messageId),
    JSON.stringify({
      connectionId,
      expiresAt: now + TTL_MS,
      observedAt: now,
      cacheGroupTag: cacheGroupTag && /^[a-f0-9]{64}$/.test(cacheGroupTag) ? cacheGroupTag : null,
    })
  );
  if (now - lastPrunedAt >= 5 * 60_000) {
    // Values are generated by this module; validation in the query also tolerates legacy corruption.
    db.prepare(
      "DELETE FROM key_value WHERE namespace = ? AND CASE WHEN json_valid(value) THEN COALESCE(json_extract(value, '$.expiresAt'), 0) <= ? ELSE 1 END"
    ).run(NAMESPACE, now);
    db.prepare(
      `DELETE FROM key_value WHERE namespace = ? AND key NOT IN (
      SELECT key FROM key_value WHERE namespace = ? ORDER BY json_extract(value, '$.observedAt') DESC LIMIT ?
    )`
    ).run(NAMESPACE, NAMESPACE, MAX_RECORDS);
    lastPrunedAt = now;
  }
}

function getOwnerRecord(
  sessionId: string | null,
  messageId: unknown,
  now: number
): { connectionId: string; cacheGroupTag?: string } | null {
  if (!sessionId || typeof messageId !== "string" || !/^msg_[A-Za-z0-9_-]{1,200}$/.test(messageId))
    return null;
  try {
    const row = getDbInstance()
      .prepare("SELECT value FROM key_value WHERE namespace = ? AND key = ?")
      .get(NAMESPACE, key(sessionId, messageId)) as { value: string } | undefined;
    const value = row ? JSON.parse(row.value) : null;
    return typeof value?.connectionId === "string" &&
      Number.isFinite(value.expiresAt) &&
      value.expiresAt > now
      ? value
      : null;
  } catch {
    return null;
  }
}

export function getNativeClaudeThreadOwner(
  sessionId: string | null,
  messageId: unknown,
  now = Date.now()
): string | null {
  return getOwnerRecord(sessionId, messageId, now)?.connectionId ?? null;
}

export function getNativeClaudeThreadCacheGroup(
  sessionId: string | null,
  messageId: unknown
): string | null {
  const tag = getOwnerRecord(sessionId, messageId, Date.now())?.cacheGroupTag;
  return typeof tag === "string" && /^[a-f0-9]{64}$/.test(tag) ? tag : null;
}
